SELECT
    PROJECT_ID
    ,ROUND(AVG(EXPERIENCE_YEARS),2) AS AVERAGE_YEARS
    -- ,AVG((COALESCE(EXPERIENCE_YEARS,0)) 
FROM EMPLOYEE AS E 
    LEFT OUTER JOIN PROJECT AS P
     ON E.EMPLOYEE_ID=P.EMPLOYEE_ID
    WHERE PROJECT_ID IS NOT NULL 
    GROUP BY PROJECT_ID 
    ORDER BY PROJECT_ID ASC