    contest_id,
    -- COUNT(DISTINCT USER_ID) AS participant_count,
    ROUND((COUNT(DISTINCT USER_ID) * 100.0 / (SELECT total_users FROM Total_Count)),2) AS PERCENTAGE 
FROM REGISTER
    GROUP BY contest_id
