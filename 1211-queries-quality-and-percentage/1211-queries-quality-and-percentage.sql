WITH Q1 AS (
SELECT QUERY_NAME
    ,POSITION 
    ,RATING
    ,ROUND(AVG(ABS(RATING/POSITION)),2) AS QUALITY
    ,COUNT(RATING) AS TOTAL_QUERIES
    ,COUNT(CASE WHEN rating < 3 THEN 1 END) AS POOR_RATING
FROM QUERIES 
    GROUP BY QUERY_NAME
)

SELECT 
QUERY_NAME
,QUALITY
,ROUND(POOR_RATING/TOTAL_QUERIES*100,2) AS POOR_QUERY_PERCENTAGE 
FROM Q1